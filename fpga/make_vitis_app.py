#!/usr/bin/env python3
"""make_vitis_app.py - collect one recipe's sources into a folder that you
import into a Vitis "Empty Application (C)" on the MicroBlaze platform.

Usage:
  fpga/make_vitis_app.py --recipe mayo-MAYO_1-ref --out ~/vitis_src/mayo1
  fpga/make_vitis_app.py --recipe mayo-MAYO_1-ref --out ~/vitis_src/mayo1 --plan "sizes;kat 2;stack;speed 100 2"

Writes:
  OUT/src/...        scheme, harness and platform sources, flat
  OUT/main.c         runs the plan, prints DONE
  OUT/defines.txt    the -D options to paste into the Vitis compiler settings
  OUT/README.txt     the Vitis steps for this app
"""
import argparse
import json
import os
import shutil
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOP = os.path.dirname(HERE)
H = os.path.join(TOP, "harness")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--recipe", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--plan", default="sizes;kat 2;stack;speed 100 2")
    ap.add_argument("--set", action="append", default=[])
    a = ap.parse_args()
    cmd = [sys.executable, os.path.join(TOP, "tools", "hbuild.py"), "--recipe", a.recipe, "--platform", "microblaze"]
    for s in a.set:
        cmd += ["--set", s]
    if subprocess.run(cmd).returncode != 0:
        sys.exit("staging failed")
    man = json.load(open(os.path.join(TOP, "build", "microblaze", a.recipe, "manifest.json")))
    out = os.path.abspath(os.path.expanduser(a.out))
    shutil.rmtree(out, ignore_errors=True)
    src = os.path.join(out, "src")
    os.makedirs(src)

    # Vitis compiles every .c in the application's src folder, so copy
    # only what the recipe compiles, plus every header the include dirs hold.
    seen = {}
    def put(path):
        b = os.path.basename(path)
        if b in seen and seen[b] != path:
            sys.exit("two files named %s; this recipe needs folders, use the GUI include paths" % b)
        seen[b] = path
        shutil.copy2(path, os.path.join(src, b))
    stage = os.path.join(TOP, "build", "microblaze", a.recipe)
    tree = os.path.join(stage, "tree")
    inc_rel = []
    if os.path.isdir(tree):
        # Tree recipe: keep folders, because sources use relative includes.
        for d in sorted(set(man["include_dirs"])):
            if d.startswith(tree):
                dst = os.path.join(src, "tree", os.path.relpath(d, tree))
                os.makedirs(dst, exist_ok=True)
                for f in os.listdir(d):
                    full = os.path.join(d, f)
                    if os.path.isfile(full) and (f.endswith((".h", ".inc", ".macros")) or full in man["sources"]):
                        shutil.copy2(full, dst)
                inc_rel.append(os.path.relpath(dst, src))
        for d in man["include_dirs"]:
            if not d.startswith(tree) and os.path.isdir(d):
                for f in os.listdir(d):
                    if f.endswith((".h", ".inc", ".macros")):
                        put(os.path.join(d, f))
        for s in man["harness_sources"]:
            put(s)
    else:
        for d in man["include_dirs"]:
            if os.path.isdir(d):
                for f in os.listdir(d):
                    if f.endswith((".h", ".inc", ".macros")):
                        put(os.path.join(d, f))
        for s in man["sources"] + man["harness_sources"]:
            put(s)
    for f in ("bench_main.c", "hsha256.c", "hsha256.h"):
        put(os.path.join(H, "src", f))
    put(os.path.join(H, "platform", "plat_microblaze.c"))

    plan = [p.strip().split() for p in a.plan.split(";") if p.strip()]
    with open(os.path.join(src, "main.c"), "w") as f:
        f.write("/* Generated by fpga/make_vitis_app.py. Plan: %s */\n" % a.plan)
        f.write("#include <stdio.h>\nint harness_run(int argc, char **argv);\n")
        for i, p in enumerate(plan):
            f.write("static char *plan_%d[] = { \"bench\", %s };\n" % (i, ", ".join('"%s"' % x for x in p)))
        f.write("int main(void)\n{\n")
        for i, p in enumerate(plan):
            f.write("    harness_run(%d, plan_%d);\n" % (len(p) + 1, i))
        f.write('    printf("DONE\\r\\n");\n    return 0;\n}\n')
    defs = list(man["defines"]) + list(man.get("bench_defines", []))
    ident = ['HARNESS_SCHEME="%s"' % man["scheme"], 'HARNESS_PARAM="%s"' % man["param"],
             'HARNESS_VARIANT="%s"' % man["variant"], 'HARNESS_PLATFORM="microblaze"',
             'HARNESS_CFLAGS="-O3 %s"' % " ".join("-D" + d for d in man["defines"]).replace(",", "|").replace('"', "")]
    with open(os.path.join(out, "defines.txt"), "w") as f:
        for d in defs + ident:
            f.write("-D%s\n" % d)
    with open(os.path.join(out, "includes.txt"), "w") as f:
        f.write("${workspace_loc:/${ProjName}/src}\n")
        for d in inc_rel:
            f.write("${workspace_loc:/${ProjName}/src/%s}\n" % d)
    with open(os.path.join(out, "README.txt"), "w") as f:
        f.write("""Vitis steps for %s
1. Vitis: File > New > Platform Component, XSA = pqsig_mb.xsa, OS standalone, CPU microblaze_0.
2. File > New > Application, template "Empty Application (C)", on that platform.
3. Copy everything from src/ into the application's src folder.
4. Application settings > C/C++ build > Compiler > Symbols: add each line of defines.txt.
   Directories: add each line of includes.txt.
   Optimisation: -O3.
5. Linker script (lscript.ld): put .text, .data, .bss, heap and stack in the DDR
   region (mig_7series_0_memaddr). Heap 0x4000000 (64 MB), stack 0x100000 (1 MB).
   Larger keys need a larger heap; the harness prints ERROR,...,alloc_failed if not.
6. Build, program the FPGA, run. Capture output with:
   tools/esp32_capture.py --port /dev/ttyUSB1 --baud 115200 --out results/mb_%s.csv
""" % (a.recipe, a.recipe))
    print("Vitis app sources written to", out)


if __name__ == "__main__":
    main()
