#!/usr/bin/env python3
"""kat_checklist.py - KAT checklist (Markdown) from kat_all.py
output.

  tools/kat_checklist.py results/kat_x86.csv > kat_checklist_x86.md
  tools/kat_checklist.py results/kat_pi5_cat1.csv results/kat_x86_cat1.csv > results/kat_checklist_boards.md

Accepts kat_all.py console logs (name status detail) named
kat_<platform>_*.log, or its CSV files. A later line for the same recipe
and platform replaces an earlier one, so give the files oldest first.
"""
import csv
import json
import os
import re
import sys

TOP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main(paths):
    rec = json.load(open(os.path.join(TOP, "registry", "recipes.json")))["recipes"]
    status = {}
    for p in paths:
        base = os.path.basename(p)
        if p.endswith(".csv"):
            for r in csv.DictReader(open(p)):
                status[(r["recipe"], r["platform"])] = (r["status"], r["detail"])
            continue
        m = re.match(r"kat_([a-z0-9-]+?)_", base)
        plat = m.group(1) if m else "unknown"
        for line in open(p):
            parts = line.split(None, 2)
            if len(parts) >= 2 and parts[0] in rec and parts[1] in ("PASS", "FAIL", "EXTERNAL", "BUILD_FAIL"):
                status[(parts[0], plat)] = (parts[1], parts[2].strip() if len(parts) > 2 else "")
    plats = sorted({k[1] for k in status})
    print("# KAT checklist\n")
    print("Generated by `tools/kat_checklist.py` from: " + ", ".join("`%s`" % os.path.basename(p) for p in paths) + ".\n")
    print("PASS: the harness reproduces the team's known-answer data. EXTERNAL: checked against an independent source "
          "(ACVP, RFC 8032, OpenSSL, the library's own suite). BUILD_FAIL and FAIL rows name the reason.\n")
    counts = {}
    for (r, p), (st, _) in status.items():
        counts.setdefault(p, {}).setdefault(st, 0)
        counts[p][st] += 1
    print("| Platform | " + " | ".join(["PASS", "EXTERNAL", "FAIL", "BUILD_FAIL"]) + " |")
    print("|---|---|---|---|---|")
    for p in plats:
        c = counts[p]
        print("| %s | %d | %d | %d | %d |" % (p, c.get("PASS", 0), c.get("EXTERNAL", 0), c.get("FAIL", 0), c.get("BUILD_FAIL", 0)))
    print()
    print("| Recipe | Scheme | Variant | " + " | ".join(plats) + " |")
    print("|---|---|---|" + "---|" * len(plats))
    for r in sorted({k[0] for k in status}, key=lambda n: (rec[n]["scheme"], n)):
        cells = []
        for p in plats:
            st = status.get((r, p))
            cells.append(st[0] if st else "")
        print("| `%s` | %s | %s | %s |" % (r, rec[r]["scheme"], rec[r]["variant"], " | ".join(cells)))
    bad = [(k, v) for k, v in status.items() if v[0] in ("FAIL", "BUILD_FAIL")]
    if bad:
        print("\n## Failures\n")
        for (r, p), (st, det) in sorted(bad):
            print("- `%s` on %s: %s, %s" % (r, p, st, det[:300]))


if __name__ == "__main__":
    main(sys.argv[1:])
